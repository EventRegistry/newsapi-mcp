#!/usr/bin/env node
// Writes src/skills/content.ts, the served skills embedded as text so the npm
// bundle and the Docker bundle carry them without reading src/skills at run
// time. Each distinct file text is written once; SKILL_FILES maps every
// "<skill>/<path>" to its text, the record memorySkillFiles() takes.
// tests/skills-content.test.ts fails when the module is out of date.
//
//   npm run build:skill-content   # rewrites src/skills/content.ts
import { writeFileSync } from "fs";
import { join } from "path";
import { argv, stdout } from "process";
import { fileURLToPath } from "url";
import { SKILLS_DIR, readSkillSources, selfContainedSkills } from "./skill-transform.js";

// a top-level file of src/skills, so the transform leaves it out of every skill
const CONTENT_FILE = join(SKILLS_DIR, "content.ts");

/**
 * Joins each skill's files into one record keyed by "<skill>/<path>".
 * @param {Record<string, Record<string, string>>} skills as selfContainedSkills returns
 * @returns {Record<string, string>} file text by "<skill>/<path>"
 */
export function flatSkillFiles(skills) {
  return Object.fromEntries(
    Object.entries(skills).flatMap(([name, files]) =>
      Object.entries(files).map(([path, text]) => [`${name}/${path}`, text]),
    ),
  );
}

/**
 * Renders the TypeScript module that embeds the skills.
 * @param {Record<string, Record<string, string>>} skills as selfContainedSkills returns
 * @returns {string} the module source
 */
export function renderSkillContent(skills) {
  // group the paths that share one text
  const pathsByText = new Map();
  for (const [path, text] of Object.entries(flatSkillFiles(skills))) {
    pathsByText.set(text, [...(pathsByText.get(text) ?? []), path]);
  }

  // name a shared text after its path in the skills, any other after its full path
  const nameByText = new Map();
  for (const [text, paths] of pathsByText) {
    const inSkill = new Set(paths.map((path) => path.slice(path.indexOf("/") + 1)));
    const isShared = paths.length > 1 && inSkill.size === 1;
    const base = constantName(isShared ? [...inSkill][0] : paths[0]);
    let name = base;
    for (let n = 2; [...nameByText.values()].includes(name); n++) name = `${base}_${n}`;
    nameByText.set(text, name);
  }

  const constants = [...nameByText].map(([text, name]) => `const ${name} = ${JSON.stringify(text)};\n`);
  const entries = [...pathsByText].flatMap(([text, paths]) =>
    paths.map((path) => `  ${JSON.stringify(path)}: ${nameByText.get(text)},\n`),
  );
  return [
    "// Generated by scripts/generate-skill-content.js from src/skills; do not edit.\n",
    "// Run `npm run build:skill-content` after changing a skill.\n",
    "\n",
    ...constants,
    "\n",
    '/** The served skill files: text by "<skill>/<path>", as memorySkillFiles() takes them. */\n',
    "export const SKILL_FILES: Readonly<Record<string, string>> = Object.freeze({\n",
    ...entries.sort(),
    "});\n",
  ].join("");
}

function constantName(path) {
  return path.replace(/[^A-Za-z0-9]+/g, "_").toUpperCase();
}

if (argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(CONTENT_FILE, renderSkillContent(selfContainedSkills(readSkillSources())));
  stdout.write("src/skills/content.ts\n");
}
